function isIndustryKey(value: string): value is IndustryKey {
  return Object.prototype.hasOwnProperty.call(INDUSTRY_PRESETS, value);
}

/** 不明・未設定のキーは other にフォールバックする。 */
export function getPreset(key: string | null | undefined): IndustryPreset {
  if (!key) return INDUSTRY_PRESETS.other;
  const normalized = key.trim();
  return isIndustryKey(normalized) ? INDUSTRY_PRESETS[normalized] : INDUSTRY_PRESETS.other;
}
